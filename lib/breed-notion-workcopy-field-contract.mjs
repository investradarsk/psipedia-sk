const active = new Set(BREED_WORKCOPY_EDITORIAL_PROPERTIES);
const known = new Set(BREED_WORKCOPY_PHYSICAL_PROPERTIES);

/** Resolve a legacy Admin schema name to its UNIQUE current Notion column. */
export function breedWorkcopyPhysicalProperty(logicalNotionName) {
  if (typeof logicalNotionName !== "string" || excludedLegacy.has(logicalNotionName)) return null;
  const name = Object.hasOwn(mapped, logicalNotionName) ? mapped[logicalNotionName] : logicalNotionName;
  return active.has(name) ? name : null;
}

export const BREED_WORKCOPY_NON_EDITORIAL_COLUMNS = Object.freeze([
  ...BREED_WORKCOPY_TECHNICAL_PROPERTIES,
  ...BREED_WORKCOPY_HISTORICAL_PROPERTIES,
]);

export function breedWorkcopyPropertyKind(name) {
  if (!known.has(name)) return null;
  if (BREED_WORKCOPY_TECHNICAL_PROPERTIES.includes(name)) return "technical";
  if (BREED_WORKCOPY_HISTORICAL_PROPERTIES.includes(name)) return "historical";
  if (BREED_CONTROLLED_FIELDS.some(field => field.notion === name)) return "controlled";
  return name === "FCI číslo" || active.has(name) ? "content" : null;
}
