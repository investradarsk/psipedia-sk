import assert from "node:assert/strict";
import fs from "node:fs/promises";

const root = new URL("../", import.meta.url);
const sourceUrl = new URL("data/imports/help-organizations-ready-2026-09-10.json", root);
const outputUrl = new URL("drizzle/0037_import_ready_help_organizations.sql", root);
const data = JSON.parse(await fs.readFile(sourceUrl, "utf8"));

const allowedTypes = new Set(["SHELTER", "CIVIC_ASSOCIATION", "RESCUE_ORGANIZATION", "MUNICIPAL_ORGANIZATION", "NONPROFIT", "OTHER"]);
const expectedHoldSlugs = new Set([
  "pomoc-kvetoslava-slana",
  "pomoc-labka-pomoci-o-z",
  "pomoc-mesto-banska-bystrica",
  "pomoc-oz-horsky-ranc",
  "pomoc-oz-majme-srdce",
  "pomoc-mesto-roznava",
  "pomoc-zivot-je-pes-o-z",
  "pomoc-mvdr-ivan-institoris",
  "pomoc-rc-sloboda-zvierat-nitra",
  "pomoc-labky-v-nudzi-odchytove-koterce-samorin",
]);

assert.equal(data.readyCount, 106, "The reviewed source must declare exactly 106 READY organizations.");
assert.equal(data.holdCount, 10, "The reviewed source must declare exactly 10 HOLD organizations.");
assert.equal(data.organizations.length, 106, "The import must contain exactly 106 organizations.");
assert.deepEqual(new Set(data.excludedHoldSlugs), expectedHoldSlugs, "The HOLD manifest changed.");
assert.equal(new Set(data.organizations.map((row) => row.slug)).size, 106, "Canonical slugs must be unique.");
assert.equal(new Set(data.organizations.map((row) => row.importKey)).size, 106, "Import keys must be unique.");
assert.equal(data.organizations.filter((row) => row.directoryProfile).length, 1, "Exactly one reviewed directory link is allowed.");

for (const row of data.organizations) {
  assert.match(row.slug, /^[a-z0-9]+(?:-[a-z0-9]+)*$/, `Invalid slug: ${row.slug}`);
  assert.equal(row.importKey, `help-org:${row.slug}`, `Unstable import key: ${row.slug}`);
  assert.equal(row.status, "DRAFT", `Non-draft import row: ${row.slug}`);
  assert.equal(row.publishedAt, null, `publishedAt must be null: ${row.slug}`);
  assert.equal(row.archivedAt, null, `archivedAt must be null: ${row.slug}`);
  assert.ok(allowedTypes.has(row.type), `Unsupported organization type: ${row.slug}`);
  assert.ok(!expectedHoldSlugs.has(row.slug), `HOLD row leaked into import: ${row.slug}`);
}

const columns = [
  "name", "slug", "legal_name", "registration_number", "type", "status", "short_description", "description",
  "public_email", "public_phone", "website_url", "facebook_url", "instagram_url", "address", "city", "district", "region",
  "country_code", "image_url", "image_key", "directory_profile_id", "import_key", "source_url", "source_data_json", "seo_json",
  "published_at", "last_verified_at", "archived_at", "created_at", "updated_at", "created_by", "updated_by",
];

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function directoryLookup(profile) {
  if (!profile) return "NULL";
  const where = `category = ${sql(profile.category)} AND slug = ${sql(profile.slug)}`;
  return `CASE WHEN (SELECT COUNT(*) FROM directory_profiles WHERE ${where}) = 1 THEN (SELECT id FROM directory_profiles WHERE ${where}) ELSE NULL END`;
}

function values(row) {
  return [
    row.name, row.slug, row.legalName, row.registrationNumber, row.type, row.status, row.shortDescription, row.description,
    row.publicEmail, row.publicPhone, row.websiteUrl, row.facebookUrl, row.instagramUrl, row.address, row.city, row.district, row.region,
    row.countryCode, row.imageUrl, row.imageKey,
  ].map(sql).concat([
    directoryLookup(row.directoryProfile), sql(row.importKey), sql(row.sourceUrl), sql(JSON.stringify(row.sourceData)), sql(JSON.stringify(row.seo)),
    sql(row.publishedAt), sql(row.lastVerifiedAt), sql(row.archivedAt), sql(row.createdAt), sql(row.updatedAt), sql(row.createdBy), sql(row.updatedBy),
  ]).join(", ");
}

const identities = data.organizations.map((row) => `(${sql(row.importKey)}, ${sql(row.slug)}, ${sql(row.name)})`).join(",\n    ");
const selectColumns = columns.map((column) => `source.${column}`).join(", ");
const chunks = [];
for (let index = 0; index < data.organizations.length; index += 20) chunks.push(data.organizations.slice(index, index + 20));
const inserts = chunks.map((chunk) => {
  const rows = chunk.map((row) => `(${values(row)})`).join(",\n    ");
  return `WITH source(${columns.join(", ")}) AS (
  VALUES
    ${rows}
)
INSERT INTO help_organizations (${columns.join(", ")})
SELECT ${selectColumns}
FROM source
WHERE NOT EXISTS (
  SELECT 1
  FROM help_organizations existing
  WHERE existing.import_key = source.import_key
    AND existing.slug = source.slug
    AND existing.name = source.name
);`;
}).join("\n\n");

const migration = `-- Generated by scripts/generate-help-organizations-import.mjs.
-- Authoritative selection: 106 READY rows from Psipedia_pomoc_psom_final_verification_2026-09-10.xlsx.
-- The 10 HOLD rows are excluded by the checked-in manifest and generator assertions.

WITH source(import_key, slug, name) AS (
  VALUES
    ${identities}
)
INSERT INTO help_organizations (
  name, slug, type, status, import_key, created_at, updated_at, created_by, updated_by
)
SELECT
  '__IMPORT_IDENTITY_CONFLICT__', '__import_identity_conflict__', 'OTHER', 'CONFLICT',
  '__import_identity_conflict__', '2026-09-15T00:00:00.000Z', '2026-09-15T00:00:00.000Z',
  'canonical-import:help-organizations-v1', 'canonical-import:help-organizations-v1'
WHERE EXISTS (
  SELECT 1
  FROM source
  JOIN help_organizations existing
    ON existing.import_key = source.import_key OR existing.slug = source.slug
  WHERE existing.import_key <> source.import_key
     OR existing.slug <> source.slug
     OR existing.name <> source.name
);

${inserts}
`;

await fs.writeFile(outputUrl, migration);
