import assert from "node:assert/strict";
import fs from "node:fs/promises";
import {
  ADOPTION_HOLD_SLUGS,
  ADOPTION_ORGANIZATION_IDENTITIES,
  preflightAdoptionMigration,
} from "../lib/adoption-migration-safety.ts";

const root = new URL("../", import.meta.url);
const manifestUrl = new URL("data/imports/adoptions-ready-2026-09-13.json", root);
const outputUrl = new URL("drizzle/0038_adoption_staging_data.sql", root);
const manifest = JSON.parse(await fs.readFile(manifestUrl, "utf8"));

const legacyFixture = manifest.ready.map((row) => ({
  category: "adopcia",
  slug: row.slug,
  status: "published",
  excerpt: row.excerpt,
  description: row.description ?? "",
  dogName: row.dogName,
  breed: row.breed,
  imageUrl: row.imageUrl,
}));
const organizationFixture = Object.values(ADOPTION_ORGANIZATION_IDENTITIES).map((identity, index, rows) => ({
  id: rows.length + index + 1,
  importKey: identity.importKey,
  slug: identity.slug,
  name: identity.name,
}));
const report = preflightAdoptionMigration(manifest, legacyFixture, organizationFixture, []);
assert.equal(report.ready, 36);
assert.equal(report.holdCandidatesImported, 0);
assert.equal(report.canonicalMappings, 36);
assert.equal(report.organizationIdentities, 4);
assert.deepEqual(Object.values(report.distribution), [16, 9, 7, 4]);
assert.equal(report.publicationBlockers.length, 0);

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
}

const sourceColumns = [
  "name", "slug", "status", "sex", "birth_date", "approximate_age_months", "size", "weight",
  "breed_name", "use_legacy_breed", "breed_mix", "region", "district", "city", "organization_import_key",
  "expected_organization_name", "expected_organization_slug", "main_image", "short_description", "description",
  "use_legacy_description", "external_source_url", "contact_email", "contact_phone", "contact_url", "search_text",
  "last_verified_at",
];

const sourceRows = report.candidates.map((candidate) => {
  const raw = manifest.ready.find((row) => row.slug === candidate.slug);
  const identity = Object.values(ADOPTION_ORGANIZATION_IDENTITIES).find((row) => row.importKey === candidate.organizationImportKey);
  assert.ok(raw && identity, `Missing source identity for ${candidate.slug}`);
  return [
    candidate.name, candidate.slug, candidate.status, candidate.sex, candidate.birthDate, candidate.approximateAgeMonths,
    candidate.size, candidate.weight, candidate.breedName, raw.breed === null ? 1 : 0, candidate.breedMix ? 1 : 0,
    candidate.region, candidate.district, candidate.city, candidate.organizationImportKey, identity.name, identity.slug,
    candidate.mainImage, candidate.shortDescription, candidate.description, raw.description === null ? 1 : 0,
    candidate.externalSourceUrl, candidate.contactEmail, candidate.contactPhone, candidate.contactUrl, candidate.searchText,
    candidate.lastVerifiedAt,
  ].map(sql).join(", ");
});

const holdSql = ADOPTION_HOLD_SLUGS.map(sql).join(", ");
const distributionChecks = Object.values(ADOPTION_ORGANIZATION_IDENTITIES)
  .map((identity) => `(SELECT COUNT(*) FROM __psipedia_adoption_staging_source_0038 WHERE organization_import_key = ${sql(identity.importKey)}) = ${identity.expectedCount}`)
  .join("\n    AND ");

const migration = `-- Generated by scripts/generate-adoption-staging-migration.mjs.
-- Data-only staging import: exactly 36 reviewed READY adoptions, all DRAFT and unpublished.
-- Runtime identity and legacy lookups fail before the first adoption_dogs INSERT.

DROP TABLE IF EXISTS __psipedia_adoption_staging_source_0038;
CREATE TABLE __psipedia_adoption_staging_source_0038 (
  ${sourceColumns.map((column) => `${column} ${["approximate_age_months", "use_legacy_breed", "breed_mix", "use_legacy_description"].includes(column) ? "INTEGER" : column === "weight" ? "REAL" : "TEXT"}`).join(",\n  ")}
);

INSERT INTO __psipedia_adoption_staging_source_0038 (${sourceColumns.join(", ")}) VALUES
  (${sourceRows.join("),\n  (")});

DROP TABLE IF EXISTS __psipedia_adoption_staging_guard_0038;
CREATE TABLE __psipedia_adoption_staging_guard_0038 (
  ok INTEGER NOT NULL CHECK (ok = 1)
);

-- One failing condition writes 0 into the CHECK-constrained guard and aborts
-- the migration before adoption_dogs is touched. There is no skip or upsert path.
INSERT INTO __psipedia_adoption_staging_guard_0038 (ok)
SELECT CASE WHEN
  (SELECT COUNT(*) FROM __psipedia_adoption_staging_source_0038) = 36
  AND (SELECT COUNT(DISTINCT slug) FROM __psipedia_adoption_staging_source_0038) = 36
  AND (SELECT COUNT(DISTINCT organization_import_key) FROM __psipedia_adoption_staging_source_0038) = 4
  AND NOT EXISTS (SELECT 1 FROM __psipedia_adoption_staging_source_0038 WHERE status <> 'DRAFT')
  AND NOT EXISTS (SELECT 1 FROM __psipedia_adoption_staging_source_0038 WHERE slug IN (${holdSql}))
  AND NOT EXISTS (
    SELECT 1 FROM __psipedia_adoption_staging_source_0038 source
    WHERE EXISTS (SELECT 1 FROM adoption_dogs target WHERE target.slug = source.slug)
  )
  AND NOT EXISTS (
    SELECT 1 FROM __psipedia_adoption_staging_source_0038 source
    WHERE (SELECT COUNT(*) FROM help_cases legacy
      WHERE legacy.category = 'adopcia' AND legacy.status = 'published' AND legacy.slug = source.slug) <> 1
  )
  AND NOT EXISTS (
    SELECT 1 FROM __psipedia_adoption_staging_source_0038 source
    WHERE (SELECT COUNT(*) FROM help_organizations organization
      WHERE organization.import_key = source.organization_import_key
        AND organization.slug = source.expected_organization_slug
        AND organization.name = source.expected_organization_name) <> 1
  )
  AND ${distributionChecks}
THEN 1 ELSE 0 END;

INSERT INTO adoption_dogs (
  name, slug, status, sex, birth_date, approximate_age_months, size, weight, breed_id, breed_name, breed_mix,
  region, district, city, organization_id, organization_name, organization_slug, main_image, gallery_json,
  short_description, description, external_source_url, contact_email, contact_phone, contact_url, search_text,
  published_at, last_verified_at, created_at, updated_at, created_by, updated_by
)
SELECT
  source.name, source.slug, 'DRAFT', source.sex, source.birth_date, source.approximate_age_months, source.size, source.weight,
  NULL, CASE WHEN source.use_legacy_breed = 1 THEN legacy.breed ELSE source.breed_name END, source.breed_mix,
  source.region, source.district, source.city, organization.id, organization.name, organization.slug,
  COALESCE(legacy.image_url, source.main_image), '[]', source.short_description,
  CASE WHEN source.use_legacy_description = 1 THEN legacy.description ELSE source.description END,
  source.external_source_url, source.contact_email, source.contact_phone, source.contact_url, source.search_text,
  NULL, source.last_verified_at, legacy.created_at, legacy.updated_at,
  'adoption-staging-import:v1', 'adoption-staging-import:v1'
FROM __psipedia_adoption_staging_source_0038 source
JOIN help_cases legacy
  ON legacy.category = 'adopcia' AND legacy.status = 'published' AND legacy.slug = source.slug
JOIN help_organizations organization
  ON organization.import_key = source.organization_import_key
  AND organization.slug = source.expected_organization_slug
  AND organization.name = source.expected_organization_name;

-- Postcondition failure also rolls the migration back as one D1 migration unit.
INSERT INTO __psipedia_adoption_staging_guard_0038 (ok)
SELECT CASE WHEN
  (SELECT COUNT(*) FROM adoption_dogs target JOIN __psipedia_adoption_staging_source_0038 source ON source.slug = target.slug) = 36
  AND (SELECT COUNT(*) FROM adoption_dogs target JOIN __psipedia_adoption_staging_source_0038 source ON source.slug = target.slug
    WHERE target.status = 'DRAFT' AND target.published_at IS NULL AND target.organization_id IS NOT NULL) = 36
  AND (SELECT COUNT(DISTINCT target.organization_id) FROM adoption_dogs target
    JOIN __psipedia_adoption_staging_source_0038 source ON source.slug = target.slug) = 4
  AND NOT EXISTS (
    SELECT 1 FROM adoption_dogs target
    JOIN __psipedia_adoption_staging_source_0038 source ON source.slug = target.slug
    JOIN help_organizations organization ON organization.id = target.organization_id
    WHERE target.organization_name <> organization.name OR target.organization_slug <> organization.slug
  )
THEN 1 ELSE 0 END;

DROP TABLE __psipedia_adoption_staging_guard_0038;
DROP TABLE __psipedia_adoption_staging_source_0038;
`;

await fs.writeFile(outputUrl, migration);
